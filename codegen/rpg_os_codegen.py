"""rpg_os-codegen: compile a ruleset JSON schema into a strongly typed C++ header.

Usage:
  python3 codegen/rpg_os_codegen.py --ruleset rulesets/dnd5e_srd.json  --out generated/
  python3 codegen/rpg_os_codegen.py --ruleset rulesets/tde5e_core.json --out generated/

Emits ``generated/<ruleset_id>_static.hpp``. The generated code is header-only,
depends only on rpg_os/common + rpg_os/core (never on the dynamic universal
engine), still reads the ruleset JSON at runtime for the *data* database
(archetypes, ...), and is clang-format clean.

Python 3, standard library only.
"""
