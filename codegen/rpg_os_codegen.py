def generate(ruleset: dict) -> str:
    return Generator(ruleset).generate()


def main() -> int:
    parser = argparse.ArgumentParser(description="RPG OS code generator")
    parser.add_argument("--ruleset", required=True, help="path to the ruleset JSON")
    parser.add_argument("--out", required=True, help="output directory")
    args = parser.parse_args()

    ruleset_path = pathlib.Path(args.ruleset)
    ruleset = json.loads(ruleset_path.read_text(encoding="utf-8"))
    header = generate(ruleset)

    ruleset_id = ruleset["ruleset_id"]
    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / f"{ruleset_id}_static.hpp"
    out_file.write_text(header, encoding="utf-8")
    print(f"wrote {out_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
